// npm install --no-save @electric-sql/pglite, then node db-test.cjs
const {PGlite}=require(process.argv[2] || '@electric-sql/pglite');
const fs=require('node:fs'),assert=require('node:assert/strict');
(async()=>{
 const db=new PGlite();
 await db.exec('create role anon; create role authenticated;');
 const sql=fs.readFileSync(__dirname+'/supabase-setup.sql','utf8');
 const installed=await db.exec(sql);
 const key=installed.flatMap(r=>r.rows||[]).find(r=>r.teacher_access_key)?.teacher_access_key;
 assert.match(key,/^[a-f0-9]{64}$/);
 assert.equal((await db.exec(sql)).flatMap(r=>r.rows||[]).length,0,'rerun does not replace teacher key');
 await db.exec('set role anon');
 const id='00000000-0000-4000-8000-000000000001', token='a'.repeat(64);
 const call=(fn,args)=>db.query(`select * from public.${fn}(${args.map((_,i)=>'$'+(i+1)).join(',')})`,args);
 const denied=async fn=>assert.rejects(fn,e=>e.code==='42501');
 await denied(()=>db.query('select * from milky_private.runs'));
 await denied(()=>db.query('select * from milky_private.teacher'));
 await assert.rejects(()=>call('milky_start',[id,token,'  ']),e=>e.code==='22023');
 await call('milky_start',[id,token,'검증용 탐정']);
 await call('milky_start',[id,token,'검증용 탐정']);
 await denied(()=>call('milky_start',[id,'b'.repeat(64),'검증용 탐정']));
 await denied(()=>call('milky_update',[id,'b'.repeat(64),[0],[],false]));
 await call('milky_update',[id,token,[0],[],false]);
 await call('milky_update',[id,token,[],[],false]);
 await assert.rejects(()=>call('milky_update',[id,token,[9],[],false]),e=>e.code==='22023');
 await assert.rejects(()=>call('milky_update',[id,token,[null],[],false]),e=>e.code==='22023');
 await assert.rejects(()=>call('milky_update',[id,token,[0],[0],false]),e=>e.code==='22023');
 await assert.rejects(()=>call('milky_update',[id,token,[0],[],true]),e=>e.code==='22023');
 const day=(await db.query("select (now() at time zone 'Asia/Seoul')::date::text as day")).rows[0].day;
 await denied(()=>call('milky_teacher',['x'.repeat(64),day]));
 await denied(()=>call('milky_teacher',[null,day]));
 let rows=(await call('milky_teacher',[key,day])).rows;
 assert.equal(rows.length,1);assert.deepEqual(rows[0].clues,[0]);assert.ok(!('token_hash' in rows[0]));
 await call('milky_update',[id,token,[0,1,2,3,4,5,6,7,8],[0,1,2],true]);
 await call('milky_update',[id,token,[0],[],false]);
 rows=(await call('milky_teacher',[key,day])).rows;
 assert.equal(rows[0].clues.length,9);assert.equal(rows[0].finished,true);
 assert.equal((await call('milky_teacher',[key,'2000-01-01'])).rows.length,0);
 await db.exec('reset role');
 assert.equal((await db.query("select count(*)::int n from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='milky_private' and c.relkind='r' and c.relrowsecurity")).rows[0].n,2);
 await db.close();console.log('PASS: real PostgreSQL setup, idempotency, token isolation, denied table access, progress validation, monotonic updates and teacher-only listing');
})().catch(e=>{console.error(e);process.exitCode=1});
